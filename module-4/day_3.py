# Lists
# - Ordered
# - Mutable
# - Allows duplicates
fruits: list = ["orange", "mangoes", "nanasi"]

# Tuples 
# - Ordered
# - Immutable (Fater than a list)
# - Allows duplicates
cords: tuple = (56, 32)

# Sets
# - Unordered
# - Immutable
# - Doesn't allow duplicates
nums = set(1, 2, 3, 4, 5)
